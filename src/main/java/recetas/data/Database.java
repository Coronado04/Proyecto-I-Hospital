package recetas.data;

import java.io.BufferedInputStream;
import java.io.File;
import java.io.FileInputStream;
import java.net.URL;
import java.sql.*;
import java.util.Properties;

public class Database {
    private static Database theInstance;
    public static Database instance(){
        if (theInstance==null){
            theInstance=new Database();
        }
        return theInstance;
    }
    public static final String PROPERTIES_FILE_NAME="/database.properties";
    Connection cnx;
    public Database(){
        cnx=this.getConnection();
    }
    public Connection getConnection(){
        try {
            Properties prop = new Properties();
            URL resourceUrl = getClass().getResource(PROPERTIES_FILE_NAME);
            File file = new File(resourceUrl.toURI());
            prop.load(new BufferedInputStream(new FileInputStream(file)));
//            try (var input = getClass().getResourceAsStream(PROPERTIES_FILE_NAME)) {
//                if (input == null) {
//                    throw new Exception("No se encontró el archivo " + PROPERTIES_FILE_NAME);
//                }
//                prop.load(input);
//            }
            String driver = prop.getProperty("database_driver");
            String server = prop.getProperty("database_server");
            String port = prop.getProperty("database_port");
            String user = prop.getProperty("database_user");
            String password = prop.getProperty("database_password");
            String database = prop.getProperty("database_name");

            String URL_conexion="jdbc:mysql://"+ server+":"+port+"/"+
                    database+"?user="+user+"&password="+password+"&serverTimezone=UTC";
            Class.forName(driver).newInstance();
            return DriverManager.getConnection(URL_conexion);
        } catch (Exception e) {
            System.err.println(e.getMessage());
            System.exit(-1);
        }
        return null;
    }

    // existente: prepara statement simple
    public PreparedStatement prepareStatement(String statement) throws SQLException {
        return cnx.prepareStatement(statement);
    }

    // NUEVO: sobrecarga para permitir flags como Statement.RETURN_GENERATED_KEYS
    public PreparedStatement prepareStatement(String statement, int autoGeneratedKeys) throws SQLException {
        return cnx.prepareStatement(statement, autoGeneratedKeys);
    }

    // (Opcional) sobrecarga para tipos de ResultSet si en el futuro se necesita:
    public PreparedStatement prepareStatement(String statement, int resultSetType, int resultSetConcurrency) throws SQLException {
        return cnx.prepareStatement(statement, resultSetType, resultSetConcurrency);
    }

    public int executeUpdate(PreparedStatement statement) {
        try {
            statement.executeUpdate();
            return statement.getUpdateCount();
        } catch (SQLException ex) {
            return 0;
        }
    }
    public ResultSet executeQuery(PreparedStatement statement){
        try {
            return statement.executeQuery();
        } catch (SQLException ex) {
            System.out.println(ex.getMessage());
        }
        return null;
    }

    public void close() throws Exception{
        if (cnx!=null && !cnx.isClosed()){
            cnx.close();
        }
    }
}